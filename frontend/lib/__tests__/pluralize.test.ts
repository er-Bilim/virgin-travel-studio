import { pluralize } from '../utils';

describe('pluralize', () => {
  it('возвращает "яблоко" для 1', () => {
    expect(pluralize(1, 'яблоко', 'яблока', 'яблок')).toBe('яблоко');
  });

  it('возвращает "яблока" для 2', () => {
    expect(pluralize(2, 'яблоко', 'яблока', 'яблок')).toBe('яблока');
  });
  it('возвращает "яблока" для 3', () => {
    expect(pluralize(3, 'яблоко', 'яблока', 'яблок')).toBe('яблока');
  });
  it('возвращает "яблока" для 4', () => {
    expect(pluralize(4, 'яблоко', 'яблока', 'яблок')).toBe('яблока');
  });

  it('возвращает "яблок" для 5', () => {
    expect(pluralize(5, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });

  it('возвращает "яблок" для 0', () => {
    expect(pluralize(0, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблок" для 10', () => {
    expect(pluralize(10, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблок" для 11', () => {
    expect(pluralize(11, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблок" для 12', () => {
    expect(pluralize(12, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблок" для 13', () => {
    expect(pluralize(13, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблок" для 14', () => {
    expect(pluralize(14, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблоко" для 21', () => {
    expect(pluralize(21, 'яблоко', 'яблока', 'яблок')).toBe('яблоко');
  });
  it('возвращает "яблока" для 22', () => {
    expect(pluralize(22, 'яблоко', 'яблока', 'яблок')).toBe('яблока');
  });
  it('возвращает "яблок" для 25', () => {
    expect(pluralize(25, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблоко" для 101', () => {
    expect(pluralize(101, 'яблоко', 'яблока', 'яблок')).toBe('яблоко');
  });
  it('возвращает "яблок" для 111', () => {
    expect(pluralize(111, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "яблоко" для 1001', () => {
    expect(pluralize(1001, 'яблоко', 'яблока', 'яблок')).toBe('яблоко');
  });
  it('возвращает "яблок" для 1000000', () => {
    expect(pluralize(1000000, 'яблоко', 'яблока', 'яблок')).toBe('яблок');
  });
  it('возвращает "градус" для -1', () => {
    expect(pluralize(-1, 'градус', 'градуса', 'градусов')).toBe('градус');
  });
  it('возвращает "градусов" для отрицательного числа', () => {
    expect(pluralize(-5 as never, 'градус', 'градуса', 'градусов')).toBe(
      'градусов',
    );
  });
  it('возвращает "градус" для отрицательного числа', () => {
    expect(pluralize(-21 as never, 'градус', 'градуса', 'градусов')).toBe(
      'градус',
    );
  });
  it('возвращает "яблока" для дробных чисел', () => {
    expect(pluralize(3.5, 'яблоко', 'яблока', 'яблок')).toBe('яблока');
  });

  it('возвращает "" для null', () => {
    expect(pluralize(null as never, 'яблоко', 'яблока', 'яблок')).toBe('');
  });
  it('возвращает "" для undefined', () => {
    expect(pluralize(undefined as never, 'яблоко', 'яблока', 'яблок')).toBe('');
  });
  it('возвращает "" для NaN', () => {
    expect(pluralize(NaN as never, 'яблоко', 'яблока', 'яблок')).toBe('');
  });
});
